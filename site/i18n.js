let LANG = "en";

function detectLang() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (fromUrl && LANGS[fromUrl]) return fromUrl;
  try {
    const saved = localStorage.getItem("opensourceai.lang");
    if (saved && LANGS[saved]) return saved;
  } catch { /* storage unavailable */ }
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const base = String(l).toLowerCase().split("-")[0];
    if (LANGS[base]) return base;
  }
  return "en";
}

// t("results", { n: 5 }) picks results_other; t("cat.llm") looks up directly. Falls back to English.
function t(key, vars = {}) {
  const dict = STRINGS[LANG] || STRINGS.en;
  let s;
  if ("n" in vars && typeof vars.n === "number" && !(key in STRINGS.en)) {
    const form = new Intl.PluralRules(LANG).select(vars.n);
    s = dict[`${key}_${vars.n === 0 ? "zero" : form}`] ?? dict[`${key}_${form}`] ?? dict[`${key}_other`]
      ?? STRINGS.en[`${key}_${new Intl.PluralRules("en").select(vars.n)}`];
  } else {
    s = dict[key] ?? STRINGS.en[key] ?? key;
  }
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? (typeof vars[k] === "number" ? num(vars[k]) : vars[k]) : m));
}

function num(n) {
  return n.toLocaleString(LANG);
}
